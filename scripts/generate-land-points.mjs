/**
 * Bakes globe land-dot positions so Globe.tsx does not rasterise
 * Natural Earth polygons on the main thread at runtime.
 *
 * Usage: node scripts/generate-land-points.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "src/components/three/data");
const RADIUS = 1.6;
const MASK_WIDTH = 1024;
const MASK_HEIGHT = 512;

const topology = JSON.parse(
  readFileSync(join(ROOT, "node_modules/world-atlas/land-110m.json"), "utf8"),
);

function latLngToVector3(lat, lng, radius) {
  const phi = ((90 - lat) * Math.PI) / 180;
  const theta = ((lng + 180) * Math.PI) / 180;
  return [
    -radius * Math.sin(phi) * Math.cos(theta),
    radius * Math.cos(phi),
    radius * Math.sin(phi) * Math.sin(theta),
  ];
}

function decodeArcs(topo) {
  const [sx, sy] = topo.transform?.scale ?? [1, 1];
  const [tx, ty] = topo.transform?.translate ?? [0, 0];
  return topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

function buildLandMask(topo) {
  const arcs = decodeArcs(topo);
  const toX = (lng) => ((lng + 180) / 360) * MASK_WIDTH;
  const toY = (lat) => ((90 - lat) / 180) * MASK_HEIGHT;
  const edges = [];

  const traceRing = (ring) => {
    const points = ring.flatMap((index) => (index < 0 ? [...arcs[~index]].reverse() : arcs[index]));
    const unwrapped = [];
    let shift = 0;
    points.forEach(([lng, lat], i) => {
      if (i > 0) {
        const delta = lng + shift - unwrapped[i - 1][0];
        if (delta > 180) shift -= 360;
        else if (delta < -180) shift += 360;
      }
      unwrapped.push([lng + shift, lat]);
    });
    const first = unwrapped[0];
    const last = unwrapped[unwrapped.length - 1];
    if (Math.abs(last[0] - first[0]) > 180) {
      const pole = first[1] < 0 ? -90 : 90;
      unwrapped.push([last[0], pole], [first[0], pole]);
    }
    for (const offset of [-360, 0, 360]) {
      const ringPts = unwrapped.map(([lng, lat]) => [toX(lng + offset), toY(lat)]);
      for (let i = 0; i < ringPts.length; i++) {
        const a = ringPts[i];
        const b = ringPts[(i + 1) % ringPts.length];
        if (a[1] !== b[1]) edges.push([a[0], a[1], b[0], b[1]]);
      }
    }
  };

  for (const geometry of topo.objects.land.geometries) {
    if (geometry.type === "Polygon") geometry.arcs.forEach(traceRing);
    else if (geometry.type === "MultiPolygon") {
      geometry.arcs.forEach((polygon) => polygon.forEach(traceRing));
    }
  }

  const coverage = new Uint8Array(MASK_WIDTH * MASK_HEIGHT);
  for (let y = 0; y < MASK_HEIGHT; y++) {
    const py = y + 0.5;
    const xs = [];
    for (const [x0, y0, x1, y1] of edges) {
      if ((y0 > py) === (y1 > py)) continue;
      xs.push(x0 + ((py - y0) / (y1 - y0)) * (x1 - x0));
    }
    xs.sort((a, b) => a - b);
    for (let i = 0; i + 1 < xs.length; i += 2) {
      const start = Math.max(0, Math.floor(xs[i]));
      const end = Math.min(MASK_WIDTH - 1, Math.floor(xs[i + 1]));
      const row = y * MASK_WIDTH;
      for (let x = start; x <= end; x++) coverage[row + x] = 1;
    }
  }

  return (lat, lng) => {
    const x = Math.min(MASK_WIDTH - 1, Math.max(0, Math.floor(toX(lng))));
    const y = Math.min(MASK_HEIGHT - 1, Math.max(0, Math.floor(toY(lat))));
    return coverage[y * MASK_WIDTH + x] === 1;
  };
}

function buildLandPositions(isLand, rows, dotsAtEquator) {
  const positions = [];
  for (let row = 0; row < rows; row++) {
    const lat = 90 - ((row + 0.5) / rows) * 180;
    const count = Math.max(1, Math.round(Math.cos((lat * Math.PI) / 180) * dotsAtEquator));
    const offset = (row % 2) * 0.5;
    for (let i = 0; i < count; i++) {
      const lng = ((i + offset) / count) * 360 - 180;
      if (!isLand(lat, lng)) continue;
      positions.push(...latLngToVector3(lat, lng, RADIUS));
    }
  }
  return new Float32Array(positions);
}

function toBase64(float32) {
  return Buffer.from(float32.buffer, float32.byteOffset, float32.byteLength).toString("base64");
}

const isLand = buildLandMask(topology);
const desktop = buildLandPositions(isLand, 200, 420);
const mobile = buildLandPositions(isLand, 150, 310);

mkdirSync(OUT_DIR, { recursive: true });

const source = `/* Auto-generated by scripts/generate-land-points.mjs — do not edit. */
const DESKTOP_B64 = "${toBase64(desktop)}";
const MOBILE_B64 = "${toBase64(mobile)}";

function decode(b64: string): Float32Array {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new Float32Array(bytes.buffer);
}

/** Memoised land-dot positions (xyz triples on the globe sphere). */
export const LAND_POINTS_DESKTOP = decode(DESKTOP_B64);
export const LAND_POINTS_MOBILE = decode(MOBILE_B64);
`;

writeFileSync(join(OUT_DIR, "landPoints.ts"), source);
console.log(
  `wrote landPoints.ts — desktop ${desktop.length / 3} dots, mobile ${mobile.length / 3} dots`,
);
